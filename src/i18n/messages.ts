type MessageParameters = Record<string, string | number>;

export function message(
  language: Language,
  key: MessageKey,
  parameters: MessageParameters = {},
) {
  return MESSAGES[language][key].replace(/\{(\w+)\}/g, (placeholder, name: string) => (
    parameters[name] === undefined ? placeholder : String(parameters[name])
  ));
}
